args <- commandArgs(trailingOnly=TRUE)
suppressPackageStartupMessages(library(DESeq2))
a <- readRDS(file.path(args[1],'objects','deseq2_analysis.rds'))
b <- readRDS(file.path(args[2],'objects','deseq2_analysis.rds'))
checks <- list()
eq <- function(x,y) isTRUE(all.equal(x,y,tolerance=1e-8))
for(n in c('primary','sensitivity_unadjusted','sensitivity_egfr')) {
  x<-a[[n]];y<-b[[n]]
  checks[[paste(n,'gene_ids')]]<-identical(rownames(x),rownames(y))
  checks[[paste(n,'sample_ids')]]<-identical(colnames(x),colnames(y))
  checks[[paste(n,'metadata')]]<-eq(as.data.frame(colData(x)),as.data.frame(colData(y)))
  checks[[paste(n,'size_factors')]]<-eq(sizeFactors(x),sizeFactors(y))
  checks[[paste(n,'dispersions')]]<-eq(dispersions(x),dispersions(y))
  checks[[paste(n,'convergence')]]<-all(S4Vectors::mcols(y)$betaConv)
  checks[[paste(n,'assay_names')]]<-identical(assayNames(x),assayNames(y))
  for(an in assayNames(x)) checks[[paste(n,'assay',an)]]<-eq(assay(x,an),assay(y,an))
}
checks[['VST matrix']]<-eq(assay(a$vst),assay(b$vst))
for(n in c('primary_results','primary_shrunken','sensitivity_unadjusted_results','sensitivity_egfr_results'))
  checks[[n]]<-eq(as.data.frame(a[[n]]),as.data.frame(b[[n]]))
x <- readRDS(file.path(args[1],'objects','go_analysis.rds'))
y <- readRDS(file.path(args[2],'objects','go_analysis.rds'))
for(n in c('higher','lower','higher_simplified','lower_simplified'))checks[[paste('GO',n)]]<-eq(as.data.frame(x[[n]]),as.data.frame(y[[n]]))
for(n in c('background','higher_ids','lower_ids','mapping'))checks[[paste('GO',n)]]<-eq(x[[n]],y[[n]])
output <- data.frame(check=names(checks),passed=unlist(checks),row.names=NULL)
write.csv(output,file.path(args[3],'model_object_comparison.csv'),row.names=FALSE)
print(output,row.names=FALSE)
stopifnot(all(output$passed))
